
import Interview from "../models/InterviewSchema.js";
import { generateInterviewQuestions } from "../services/InterviewService.js";
import { evaluateInterviewAnswers } from "../services/InterviewEvaluation.js";

export const generateInterview = async (req, res) => {

    try {

        const { jobRole, difficulty } = req.body;

        // Get the logged-in user's ID
        const userId = req.user._id || req.user.id;

        // Validate user authentication
        if (!userId) {
            return res.status(401).json({
                message: "Please login first"
            });
        }

        // Validate input
        if (!jobRole || !difficulty) {
            return res.status(400).json({
                message: "Job role and difficulty are required"
            });
        }

        // Generate questions using AI
        const aiResponse = await generateInterviewQuestions(
            jobRole,
            difficulty
        );

        // Convert AI JSON text into JavaScript object
        const parsedResponse = JSON.parse(aiResponse);

        if (
            !Array.isArray(parsedResponse.questions) ||
            parsedResponse.questions.length === 0
        ) {
            return res.status(500).json({
                message: "Invalid questions generated by AI"
            });
        }

        // Save interview in MongoDB
        const interview = await Interview.create({

            userId,
            jobRole,
            difficulty,

            questions: parsedResponse.questions,

            provider: "Gemini/Groq"

        });

        res.status(201).json({
            message: "Interview questions generated successfully",
            interview
        });

    } catch (error) {

        console.log("Interview generation error:", error.message);

        res.status(500).json({
            message: "Failed to generate interview questions",
            error: error.message
        });

    }
};



export const getMyInterviews = async (req, res) => {

    try {

        const userId = req.user._id || req.user.id;

        const interviews = await Interview.find({ userId })
            .sort({ createdAt: -1 });

        res.status(200).json({
            message: "Interviews fetched successfully",
            total: interviews.length,
            interviews
        });

    } catch (error) {

        console.log("Get interviews error:", error.message);

        res.status(500).json({
            message: "Failed to fetch interviews",
            error: error.message
        });

    }
};


// Evaluate Interview Answers
export const evaluateInterview = async (req, res) => {
    try {

        const { interviewId, answers } = req.body;
        const userId = req.user._id || req.user.id;

        // Check required data
        if (!interviewId || !Array.isArray(answers)) {
            return res.status(400).json({
                message: "Interview ID and answers are required"
            });
        }

        // Find interview belonging to logged-in user
        const interview = await Interview.findOne({
            _id: interviewId,
            userId
        });

        if (!interview) {
            return res.status(404).json({
                message: "Interview not found"
            });
        }

        // Prevent evaluating an already completed interview
        if (interview.status === "Completed") {
            return res.status(400).json({
                message: "This interview has already been evaluated"
            });
        }

        // Check whether all questions have been answered
        if (answers.length !== interview.questions.length) {
            return res.status(400).json({
                message: "Please answer all interview questions"
            });
        }

        // Prepare questions and answers for AI
        const submittedAnswers = answers.map((item) => {

            if (
                !Number.isInteger(item.questionIndex) ||
                item.questionIndex < 0 ||
                item.questionIndex >= interview.questions.length ||
                typeof item.answer !== "string" ||
                !item.answer.trim()
            ) {
                throw new Error("Invalid question index or answer");
            }

            return {
                questionIndex: item.questionIndex,
                question: interview.questions[item.questionIndex],
                answer: item.answer.trim()
            };

        });

        // Prevent duplicate question indexes
        const uniqueIndexes = new Set(
            submittedAnswers.map(item => item.questionIndex)
        );

        if (uniqueIndexes.size !== interview.questions.length) {
            return res.status(400).json({
                message: "Each question must have exactly one answer"
            });
        }

        // Send answers to AI evaluation service
        const aiResponse = await evaluateInterviewAnswers(
            interview.jobRole,
            interview.difficulty,
            submittedAnswers
        );

        const parsedResponse = JSON.parse(
            aiResponse.replace(/```json|```/g, "").trim()
        );

        const evaluations = parsedResponse.evaluations;

        if (
            !Array.isArray(evaluations) ||
            evaluations.length !== submittedAnswers.length
        ) {
            throw new Error("Invalid evaluation response from AI");
        }

        // Match AI evaluations with submitted answers
        const evaluatedAnswers = submittedAnswers.map((item) => {

            const evaluation = evaluations.find(
                result => result.questionIndex === item.questionIndex
            );

            if (
                !evaluation ||
                typeof evaluation.score !== "number" ||
                evaluation.score < 0 ||
                evaluation.score > 10 ||
                typeof evaluation.feedback !== "string"
            ) {
                throw new Error("Invalid answer evaluation from AI");
            }

            return {
                questionIndex: item.questionIndex,
                question: item.question,
                answer: item.answer,
                score: evaluation.score,
                feedback: evaluation.feedback
            };

        });

        // Calculate overall score out of 100
        const totalScore = Math.round(
            (
                evaluatedAnswers.reduce(
                    (total, item) => total + item.score,
                    0
                ) / evaluatedAnswers.length
            ) * 10
        );

        // Save evaluation in MongoDB
        interview.answers = evaluatedAnswers;
        interview.totalScore = totalScore;
        interview.overallFeedback = parsedResponse.overallFeedback;
        interview.strengths = parsedResponse.strengths;
        interview.areasToImprove = parsedResponse.areasToImprove;
        interview.status = "Completed";

        await interview.save();

        res.status(200).json({
            message: "Interview evaluated successfully",
            interview
        });

    } catch (error) {

        console.log("Interview evaluation error:", error.message);

        res.status(500).json({
            message: "Failed to evaluate interview",
            error: error.message
        });

    }
};
